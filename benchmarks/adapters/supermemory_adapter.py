"""Supermemory adapter for unbiased head-to-head evaluation.

Implements the harness ``MemorySystem`` protocol (``ingest`` + ``answer``)
on top of the official Supermemory Python SDK. Every call shape used here
is taken from Supermemory's own repository tests
(``benchmarks/supermemory/packages/docs-test/tests/``):

- ``Supermemory()`` — no-arg constructor, key from environment
  (``python/quickstart.py``)
- ``client.add(content=..., container_tag=..., customId=...)``
  (``python/quickstart.py``, ``typescript/quickstart-v2.ts``)
- ``client.documents.get(id).status`` polled to ``done`` / ``failed``
  (``typescript/quickstart-v2.ts`` ``waitUntilDone``)
- ``client.search.memories(q=..., container_tag=...,
  search_mode="memories", limit=...)`` with ``.results`` items carrying
  ``.memory`` (``python/search.py``, ``python/quickstart.py``)

Fairness rules enforced here:

1. SAME reader: answers are generated by the harness reader model
   (the ``--model`` you chose), NOT by Supermemory's stack. Only
   retrieval (what to remember / what to surface) is Supermemory's.
2. SAME prompt: the evidence-to-answer prompt mirrors
   ``MemoryEngine.answer`` (memories-only + explicit abstain instruction).
3. SAME replay: sessions ingest in chronological order, one stable
   container per run (isolation parity with ``CoreMemorySystem``).
4. ASYNC HONESTY: Supermemory ingests asynchronously (``dreaming``);
   ``ingest`` polls to ``done`` so later probes never race indexing.
   Polling time is reported, not hidden.

Requires: ``pip install supermemory`` + ``SUPERMEMORY_API_KEY``.
Without either, construction raises ``SkipError`` (fail closed).
"""

from __future__ import annotations

import os
import time
from datetime import datetime

INSTALL_HINT = "pip install supermemory"
KEY_HINT = "export SUPERMEMORY_API_KEY=... (get one at supermemory.ai)"


class SkipError(RuntimeError):
    """A contender cannot run: missing package, key, or backend."""


def _result_text(item: object) -> str:
    """Extract memory text exactly like Supermemory's own quickstart helper."""
    memory = getattr(item, "memory", None)
    if memory is not None:
        return str(memory)
    if isinstance(item, dict):
        return str(item.get("memory", item))
    return str(item)


def probe_supermemory() -> tuple[bool, str]:
    """Check whether a Supermemory run is possible. No side effects."""
    try:
        import supermemory  # noqa: F401
    except ImportError:
        return False, f"python package missing ({INSTALL_HINT})"
    if not os.environ.get("SUPERMEMORY_API_KEY"):
        return False, f"no key ({KEY_HINT})"
    try:
        import supermemory as _sm

        version = getattr(_sm, "__version__", "unknown")
    except Exception:
        version = "unknown"
    return True, f"ready (supermemory {version}, key present)"


class SupermemorySystem:
    """Supermemory behind the harness ``MemorySystem`` protocol."""

    def __init__(
        self,
        reader,
        *,
        container_tag: str = "sm-eval",
        top_k: int = 8,
        ingest_timeout_s: float = 120.0,
        poll_interval_s: float = 1.5,
    ) -> None:
        if not os.environ.get("SUPERMEMORY_API_KEY"):
            raise SkipError(f"no key ({KEY_HINT})")
        try:
            from supermemory import Supermemory
        except ImportError as exc:
            raise SkipError(f"supermemory package missing ({INSTALL_HINT})") from exc
        self._reader = reader
        self._container = container_tag
        self._top_k = top_k
        self._timeout = ingest_timeout_s
        self._poll = poll_interval_s
        # No-arg constructor, exactly as Supermemory's own quickstart.
        self._client = Supermemory()
        self.ingest_waits = 0
        self.ingest_timeouts = 0

    # --- write path ------------------------------------------------------

    def ingest(self, session) -> None:
        transcript = "\n".join(
            f"{t.role}: {t.content}" for t in session.turns
        )
        if not transcript.strip():
            return
        res = self._client.add(
            content=transcript,
            container_tag=self._container,
            customId=session.session_id,
        )
        doc_id = getattr(res, "id", None)
        if doc_id is None:
            return
        # Their stack dreams asynchronously: poll to done like their own
        # quickstart's waitUntilDone (status done / failed / timeout).
        start = time.monotonic()
        while time.monotonic() - start < self._timeout:
            doc = self._client.documents.get(doc_id)
            status = getattr(doc, "status", None)
            if status == "done":
                return
            if status == "failed":
                raise SkipError(f"supermemory ingest failed for {doc_id}")
            time.sleep(self._poll)
        self.ingest_timeouts += 1
        raise SkipError(
            f"supermemory ingest timed out after {self._timeout}s ({doc_id})"
        )

    # --- read path (same reader, same prompt shape as our engine) --------

    def answer(self, question: str, question_date: datetime) -> str:
        res = self._client.search.memories(
            q=question,
            container_tag=self._container,
            search_mode="memories",
            limit=self._top_k,
        )
        items = list(getattr(res, "results", None) or [])
        if not items:
            return _abstain(question)
        context = "\n".join(
            f"[S{i + 1}]\n{_result_text(it)}" for i, it in enumerate(items)
        )
        # Prompt mirrors MemoryEngine.answer: memories-only + abstain.
        prompt = (
            "You are a helpful assistant with access to long-term memories "
            "about the user, retrieved from a memory store. Answer the "
            "question using ONLY the memories below. If the memories do not "
            "contain enough information to answer, say so explicitly.\n"
            "Answer directly in one or two sentences. No reasoning, no "
            "preamble, no self-talk, no markdown.\n\n"
            f"<memories>\n{context}\n</memories>\n\n"
            f"Question (date: {question_date}): {question}"
        )
        return self._reader.complete([{"role": "user", "content": prompt}],
                                     temperature=0.0)


def _abstain(question: str) -> str:
    return (
        "I don't have enough information in memory to answer this question. "
        f"The memories I have do not cover: {question}"
    )
